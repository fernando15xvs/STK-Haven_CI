create or replace function public.stk_assert_coach_pro_access(
  p_coach_user_id uuid
)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.stk_entitlement_active_for_user(
    p_coach_user_id,
    'coach_pro'
  ) then
    raise exception 'Coach Pro entitlement required';
  end if;
end;
$$;

revoke all on function public.stk_assert_coach_pro_access(uuid)
  from public, anon, authenticated;

create or replace function public.stk_assert_coach_pro_client_capacity(
  p_coach_user_id uuid,
  p_exclude_relationship_id uuid default null
)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_limit integer;
  v_active integer;
begin
  perform public.stk_assert_coach_pro_access(p_coach_user_id);

  v_limit := public.stk_coach_pro_client_limit_for_user(p_coach_user_id);

  select count(*)::integer
    into v_active
    from public.stk_coach_client_relationships
   where coach_user_id = p_coach_user_id
     and status = 'active'
     and (
       p_exclude_relationship_id is null
       or id <> p_exclude_relationship_id
     );

  if v_active >= v_limit then
    raise exception 'Coach Pro client limit reached';
  end if;
end;
$$;

revoke all on function public.stk_assert_coach_pro_client_capacity(uuid, uuid)
  from public, anon, authenticated;

create or replace function public.stk_enforce_coach_pro_invitation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is not null then
    perform public.stk_assert_coach_pro_access(new.coach_user_id);
    perform public.stk_assert_coach_pro_client_capacity(new.coach_user_id);
  end if;
  return new;
end;
$$;

create or replace function public.stk_enforce_coach_pro_relationship_activation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or new.status <> 'active' then
    return new;
  end if;

  if tg_op = 'INSERT' then
    perform public.stk_assert_coach_pro_client_capacity(
      new.coach_user_id,
      new.id
    );
  elsif old.status is distinct from 'active' then
    perform public.stk_assert_coach_pro_client_capacity(
      new.coach_user_id,
      new.id
    );
  end if;

  return new;
end;
$$;

create or replace function public.stk_enforce_coach_pro_owned_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is not null
     and auth.uid() = new.coach_user_id then
    perform public.stk_assert_coach_pro_access(new.coach_user_id);
  end if;
  return new;
end;
$$;

create or replace function public.stk_enforce_coach_pro_task_comment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_coach_user_id uuid;
begin
  select task.coach_user_id
    into v_coach_user_id
    from public.stk_coach_tasks as task
   where task.id = new.task_id;

  if auth.uid() is not null
     and auth.uid() = v_coach_user_id then
    perform public.stk_assert_coach_pro_access(v_coach_user_id);
  end if;
  return new;
end;
$$;

